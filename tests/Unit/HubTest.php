<?php
/**
 * The screens of the setup, one level deeper each time: home, grid, simulator,
 * region. A scripted user chooses, the screens shown are recorded, the files
 * are real ones in a temporary tree.
 */

use OpenSim\Installer\Hub;
use OpenSim\Installer\Ui\InstallerUi;

/**
 * An interface that answers the choices from a script and records the screens.
 */
final class RecordingUi implements InstallerUi
{
    use \OpenSim\Installer\Ui\AsksForms;

    /** @var array<int,array{label:string,keys:list<string>,default:?string}> */
    public array $screens = [];
    /** @var list<string> */
    public array $notes = [];

    public function __construct(private array $script) {}

    public function intro(string $title): void {}
    public function note(string $message): void
    {
        $this->notes[] = $message;
    }
    public function entity(string $name): string
    {
        return $name;
    }

    public function warn(string $message): void
    {
        $this->notes[] = "warn: $message";
    }
    public function error(string $message): void
    {
        $this->notes[] = "error: $message";
    }
    public function outro(string $message): void {}

    public function choose(string $label, array $options, ?string $default = null, ?string $hint = null): string
    {
        $this->screens[] = [
            'label' => $label,
            'keys' => array_keys($options),
            'labels' => array_values($options),
            'default' => $default,
        ];

        return array_shift($this->script) ?? 'quit';
    }

    public function checklist(string $label, array $options, array $defaults = [], ?string $hint = null): array
    {
        return $defaults;
    }

    public function text(string $label, string $default = '', ?Closure $validate = null, ?string $hint = null): string
    {
        return $default;
    }
    public function secret(string $label, ?Closure $validate = null, ?string $hint = null): string
    {
        return '';
    }
    public function confirm(string $label, bool $default = true): bool
    {
        return $default;
    }
    public function spin(Closure $callback, string $message): mixed
    {
        return $callback();
    }
}

/**
 * A tree of setup: two cores' worth of config in a temporary home, a grid with
 * two simulators and three regions, a grid on another machine.
 */
function hub_tree()
{
    $root = test_tmp() . '/hub-' . bin2hex(random_bytes(4));
    $etc = "$root/etc";
    foreach (
        [
            "$root/home",
            "$etc/grids/alpha/sims/alpha_sim1/regions",
            "$etc/grids/alpha/sims/alpha_sim2/regions",
            "$etc/grids/beta",
            "$etc/robust.d",
            "$etc/opensim.d",
        ]
        as $dir
    ) {
        mkdir($dir, 0o755, true);
    }
    file_put_contents(
        "$root/home/.opensim.conf",
        "[Defaults]\nDefaultProfile = 0.9.3.0\n\n[0.9.3.0]\nEtcRoot = $etc\n",
    );
    file_put_contents("$etc/grids/alpha/Robust.HG.ini", "[Network]\n");
    symlink("$etc/grids/alpha/Robust.HG.ini", "$etc/robust.d/alpha.ini");
    file_put_contents(
        "$etc/grids/alpha/sims/alpha_sim1.ini",
        ";; Generated by opensim setup: simulator Sim One of the grid Alpha\n[Startup]\n",
    );
    file_put_contents("$etc/grids/alpha/sims/alpha_sim2.ini", "[Startup]\n");
    symlink("$etc/grids/alpha/sims/alpha_sim1.ini", "$etc/opensim.d/alpha_sim1.ini");
    file_put_contents("$etc/grids/alpha/sims/alpha_sim1/regions/Sim1.ini", "[Sim1]\nLocation = 1000,1000\n");
    file_put_contents("$etc/grids/alpha/sims/alpha_sim1/regions/Sim1North.ini", "[Sim1North]\nLocation = 1000,1001\n");
    file_put_contents("$etc/grids/alpha/sims/alpha_sim1/regions/Far.ini.disabled", "[Far]\nLocation = 1200,1200\n");
    file_put_contents("$etc/grids/beta/beta.conf", "[Grid]\nRemote = true\nGridNick = beta\n");

    return [$root, $etc];
}

/**
 * Runs the hub with a script of choices, in a tree.
 *
 * @param array $script Choices.
 * @return array The recording interface, the tree root.
 */
function hub_run(array $script)
{
    [$root, $etc] = hub_tree();
    $home = getenv('HOME');
    putenv("HOME=$root/home");
    $ui = new RecordingUi($script);
    try {
        (new Hub($ui))->run();
    } finally {
        putenv(false === $home ? 'HOME' : "HOME=$home");
    }

    return [$ui, $etc];
}

describe('Hub home', function () {
    test('lists core, grids, add and quit', function () {
        [$ui] = hub_run(['quit']);

        expect($ui->screens[0]['keys'])->toBe(['core', 'grid:alpha', 'grid:beta', 'add', 'quit']);
        expect($ui->screens[0]['labels'])->toBe([
            'OpenSim core [0.9.3.0]',
            'alpha',
            'beta (Robust on another machine)',
            'Add grid',
            'Quit',
        ]);
        expect($ui->screens[0]['default'])->toBe('grid:alpha');
    });
});

describe('Hub grid', function () {
    test('lists regions and actions', function () {
        [$ui] = hub_run(['grid:alpha', 'back', 'quit']);

        expect($ui->screens[1]['label'])->toBe('Grid: alpha');
        expect($ui->screens[1]['keys'])->toBe([
            'region:alpha_sim1:Far',
            'region:alpha_sim1:Sim1',
            'region:alpha_sim1:Sim1North',
            'addregion',
            'sims',
            'configure',
            'toggle',
            'back',
            'quit',
        ]);
        expect($ui->screens[1]['labels'])->toBe([
            'Far [Sim One] [disabled]',
            'Sim1 [Sim One]',
            'Sim1North [Sim One]',
            'Add region',
            'Simulators',
            'Configure grid',
            'Disable this grid',
            'Back',
            'Quit',
        ]);
    });

    test('the simulators are a pool of their own', function () {
        [$ui] = hub_run(['grid:alpha', 'sims', 'back', 'back', 'quit']);

        expect($ui->screens[2]['label'])->toBe('Simulators of alpha');
        expect($ui->screens[2]['keys'])->toBe(['sim:alpha_sim1', 'sim:alpha_sim2', 'addsim', 'back', 'quit']);
        expect($ui->screens[2]['labels'])->toBe(['Sim One', 'sim2 [disabled]', 'Add simulator', 'Back', 'Quit']);
    });

    test('a grid on another machine has no region of its own', function () {
        [$ui] = hub_run(['grid:beta', 'back', 'quit']);

        expect($ui->screens[1]['keys'])->toBe(['addregion', 'sims', 'back', 'quit']);
    });

    test('quit leaves the setup from any screen', function () {
        [$ui] = hub_run(['grid:alpha', 'sims', 'sim:alpha_sim1', 'region:Sim1', 'quit', 'unreachable']);

        expect(count($ui->screens))->toBe(5);
    });
});

describe('Hub simulator and region', function () {
    test('a simulator lists its regions', function () {
        [$ui] = hub_run(['grid:alpha', 'sims', 'sim:alpha_sim1', 'back', 'back', 'back', 'quit']);

        expect($ui->screens[3]['label'])->toBe('Simulator: Sim One');
        expect($ui->screens[3]['keys'])->toBe([
            'region:Far',
            'region:Sim1',
            'region:Sim1North',
            'addregion',
            'reconfigure',
            'toggle',
            'back',
            'quit',
        ]);
        expect($ui->screens[3]['labels'])->toBe([
            'Far [disabled]',
            'Sim1',
            'Sim1North',
            'Add region',
            'Configure sim',
            'Disable this simulator',
            'Back',
            'Quit',
        ]);
        expect($ui->screens[3]['default'])->toBe('addregion');
    });

    test('a region disabled and enabled again renames its file', function () {
        [$ui, $etc] = hub_run(['grid:alpha', 'region:alpha_sim1:Sim1', 'toggle', 'toggle', 'back', 'back', 'quit']);
        $regions = "$etc/grids/alpha/sims/alpha_sim1/regions";

        expect($ui->screens[2]['labels'])->toBe(['Reconfigure', 'Disable this region', 'Back', 'Quit']);
        expect($ui->screens[3]['labels'])->toBe(['Reconfigure', 'Enable this region', 'Back', 'Quit']);
        expect($ui->screens[4]['labels'])->toBe(['Reconfigure', 'Disable this region', 'Back', 'Quit']);
        expect(is_file("$regions/Sim1.ini"))->toBeTrue();
        expect(is_file("$regions/Sim1.ini.disabled"))->toBeFalse();
    });

    test('a simulator disabled from its screen loses its link', function () {
        [, $etc] = hub_run(['grid:alpha', 'sims', 'sim:alpha_sim1', 'toggle', 'back', 'back', 'back', 'quit']);

        expect(file_exists("$etc/opensim.d/alpha_sim1.ini") || is_link("$etc/opensim.d/alpha_sim1.ini"))->toBeFalse();
    });
});

describe('RegionState', function () {
    test('reads what a region file holds', function () {
        [, $etc] = hub_tree();
        file_put_contents(
            "$etc/Far.ini",
            "[Far]\nRegionUUID = 607c44e9-3d01-45eb-a07e-937dc72dbadb\nLocation = 1200,1200\nSizeX = 512\nInternalPort = 8015\nExternalHostName = \"play.example.org\"\n",
        );

        expect(\OpenSim\Installer\Grid\RegionState::values("$etc/Far.ini"))->toBe([
            'RegionUUID' => '607c44e9-3d01-45eb-a07e-937dc72dbadb',
            'Location' => '1200,1200',
            'SizeX' => '512',
            'InternalPort' => '8015',
            'ExternalHostName' => 'play.example.org',
        ]);
    });

    test('does not enable a region over one of the same name', function () {
        [, $etc] = hub_tree();
        $regions = "$etc/grids/alpha/sims/alpha_sim1/regions";
        file_put_contents("$regions/Far.ini", "[Far]\n");

        expect(\OpenSim\Installer\Grid\RegionState::enable("$regions/Far.ini.disabled"))->toBeNull();
    });
});

describe('GridRegistry region names', function () {
    test('are all the regions, without the case', function () {
        [, $etc] = hub_tree();

        expect(array_keys(\OpenSim\Installer\Grid\GridRegistry::fileNames("$etc/grids/alpha")))->toBe([
            'far',
            'sim1',
            'sim1north',
        ]);
    });
});
