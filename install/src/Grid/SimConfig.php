<?php

declare(strict_types=1);

namespace OpenSim\Installer\Grid;

/**
 * Writes the config of a simulator and of its regions.
 *
 * The simulator config is the only file the launcher gives to OpenSimulator.
 * It carries what makes the simulator its own (ports, database, folders,
 * estate) and includes the architecture of the grid, which brings the services
 * of the grid (see GridShared). What it does not set comes from the defaults of
 * the core. Nothing may be written in the core, so every folder OpenSimulator
 * would use by default (relative to the core) is given here.
 */
final class SimConfig
{
    public function render(SimPlan $plan): string
    {
        $architecture = $plan->gridDir . '/config-include/' . ($plan->hypergrid ? 'GridHypergrid.ini' : 'Grid.ini');
        $slug = $plan->slug;

        $lines = [
            ";; Generated by opensim setup: simulator {$plan->simName} of the grid {$plan->gridName}",
            '',
            '[Const]',
            'BinDirectory = "' . $plan->binDir() . '"',
            'BaseHostname = "' . $plan->baseHostname . '"',
            'BaseURL = "http://' . $plan->baseHostname . '"',
            'PublicPort = ' . $plan->publicPort,
            'PrivatePort = ' . $plan->privatePort,
            'PrivURL = "${Const|BaseURL}"',
            'EtcDirectory = "' . $plan->gridDir . '"',
            'DataDirectory = "' . $plan->dataDirectory . '"',
            'CacheDirectory = "' . $plan->cacheDirectory . '"',
            'LogsDirectory = "' . $plan->logsDirectory . '"',
            '',
            '[Startup]',
            'regionload_regionsdir = "' . $plan->regionsDir() . '"',
            'RegistryLocation = "${Const|DataDirectory}/registry"',
            'PIDFile = "${Const|CacheDirectory}/' . $slug . '.pid"',
            'ConsoleHistoryFile = "${Const|LogsDirectory}/' . $slug . '.OpenSimConsoleHistory.txt"',
            'crash_dir = "${Const|CacheDirectory}/crashes"',
            'DecodedSculptMapPath = "${Const|CacheDirectory}/j2kDecodeCache"',
            '',
            '[Network]',
            'http_listener_port = ' . $plan->httpPort,
            ...$plan->consolePort > 0 && $plan->consoleMode === 'rest'
                ? [
                    ';; Remote (REST) console of the simulator: every right on it, from the',
                    ';; machine that has the port, in the block of ten ports of the simulator',
                    ...$plan->consoleHost !== '' ? ['ConsoleHost = "' . $plan->consoleHost . '"'] : [],
                    'ConsoleUser = "' . $plan->consoleUser . '"',
                    'ConsolePass = "' . $plan->consolePass . '"',
                    'console_port = ' . $plan->consolePort,
                ]
                : ($plan->consolePort > 0
                    ? [
                        ';; Remote (REST) console of the simulator: not enabled, its port is kept here,',
                        ';; in the block of ten ports of the simulator (ConsoleUser, ConsolePass, console_port)',
                        ';console_port = ' . $plan->consolePort,
                    ]
                    : []),
            'ExternalHostNameForLSL = "${Const|BaseHostname}"',
            '',
            '[DatabaseService]',
            'StorageProvider = "OpenSim.Data.MySQL.dll"',
            'ConnectionString = "' . $plan->connectionString() . '"',
            '',
            '[GridService]',
            'MapTileDirectory = "${Const|CacheDirectory}/maptiles"',
            '',
            '[DataSnapshot]',
            'snapshot_cache_directory = "${Const|CacheDirectory}/DataSnapshot"',
            ...$plan->registerUrl !== ''
                ? [
                    ';; The search of the grid: the simulator tells its regions to the helpers',
                    'index_sims = true',
                    'gridname = "' . $plan->gridName . '"',
                    'DATA_SRV_' . self::dataServiceName($plan) . ' = "' . $plan->registerUrl . '"',
                ]
                : [],
            '',
            ...$plan->offlineUrl !== ''
                ? [
                    ';; The offline messages are kept by the helpers of the grid',
                    '[Messaging]',
                    'OfflineMessageModule = OfflineMessageModule',
                    'OfflineMessageURL = "' . $plan->offlineUrl . '"',
                    '',
                ]
                : [],
            '[YEngine]',
            'ScriptEnginesPath = "${Const|DataDirectory}/ScriptEngines"',
            '',
            ';; OSSL is part of the standard config, as the grid sets it (its osslEnable.ini)',
            '[OSSL]',
            'Include-osslDefaultEnable = "' . $plan->gridDir . '/config-include/osslDefaultEnable.ini"',
            '',
            '[Estates]',
            'DefaultEstateName = "' . $plan->estateName . '"',
            'DefaultEstateOwnerName = "' . $plan->estateOwner . '"',
            '',
            '[Architecture]',
            'Include-Architecture = "' . $architecture . '"',
            '',
        ];

        return implode("\n", $lines);
    }

    /**
     * The name of the data service of the grid in [DataSnapshot], DATA_SRV_<name>: the nick of the grid, else its name,
     * in PascalCase (vonda: Vonda, my-grid: MyGrid). Any name does, as long as it is the only one of its kind: a
     * simulator can register to several search services (its grid, 2do...).
     */
    public static function dataServiceName(SimPlan $plan): string
    {
        $text = $plan->gridNick !== '' ? $plan->gridNick : $plan->gridName;
        $words = preg_split('/[^A-Za-z0-9]+/', Slug::ascii($text), -1, PREG_SPLIT_NO_EMPTY);
        $name = implode('', array_map('ucfirst', $words ?: []));

        return $name !== '' ? $name : 'ThisGrid';
    }

    /** The name a simulator was given, from the first line of its config, null when it has none. */
    public static function readName(string $path): ?string
    {
        $head = is_file($path) ? (string) file_get_contents($path, false, null, 0, 512) : '';

        return preg_match('/^;; Generated by opensim setup: simulator (.+) of the grid /m', $head, $m)
            ? trim($m[1])
            : null;
    }

    /** Write the config of the simulator, what it was before kept beside it. */
    public function write(SimPlan $plan): string
    {
        $path = $plan->iniPath();
        @mkdir(dirname($path), 0o755, true);
        if (is_file($path)) {
            @copy($path, "$path~");
        }
        file_put_contents($path, $this->render($plan));

        return $path;
    }

    /** The description of the first region of the simulator. */
    public function renderRegion(SimPlan $plan): string
    {
        return implode("\n", [
            ';; Generated by opensim setup',
            "[{$plan->regionName}]",
            "RegionUUID = {$plan->regionUuid}",
            "Location = {$plan->regionLocation}",
            "SizeX = {$plan->regionSize}",
            "SizeY = {$plan->regionSize}",
            "SizeZ = {$plan->regionSize}",
            'InternalAddress = 0.0.0.0',
            "InternalPort = {$plan->regionPort}",
            'ResolveAddress = False',
            "ExternalHostName = {$plan->externalHost}",
            'MaptileStaticUUID = 00000000-0000-0000-0000-000000000000',
            '',
        ]);
    }

    /** Write the region, unless a file of that name is there already (and it is not a region being changed). */
    public function writeRegion(SimPlan $plan): ?string
    {
        $path = $plan->regionIni();
        if (is_file($path) && !$plan->overwriteRegion) {
            return null;
        }
        @mkdir(dirname($path), 0o755, true);
        file_put_contents($path, $this->renderRegion($plan));

        return $path;
    }
}
